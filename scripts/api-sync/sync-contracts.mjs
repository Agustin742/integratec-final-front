import { mkdir, readFile, writeFile } from 'node:fs/promises';
import path from 'node:path';
import openapiTS, { astToString } from 'openapi-typescript';

export const DEFAULT_BACKEND_REPO = 'Agustin742/integratec-final-back';
export const DEFAULT_BACKEND_BRANCH = 'develop';

export const BACKEND_ARTIFACT_PATHS = Object.freeze({
  openapi: 'apps/api/openapi.json',
  contracts: 'packages/contracts/src/index.ts',
  realtimeState: 'apps/realtime/src/rooms/schema/generated.ts',
});

export const FRONTEND_OUTPUT_PATHS = Object.freeze({
  openapi: 'src/api/schema.generated.ts',
  contracts: 'src/realtime/contracts.generated.ts',
  realtimeState: 'src/realtime/room-state.generated.ts',
});

export const GENERATED_HEADER = [
  '/* eslint-disable */',
  '// AUTO-GENERATED by pnpm api:sync — DO NOT EDIT MANUALLY.',
].join('\n');

export class ContractSyncError extends Error {
  /**
   * @param {string} message
   * @param {{ code: 'CLI_ARG_ERROR' | 'ARTIFACT_MISSING' | 'NETWORK_ERROR' | 'INVALID_JSON' | 'INVALID_OPENAPI'; artifactPath?: string; sourceLocation?: string; cause?: unknown }} details
   */
  constructor(message, details) {
    super(message, details?.cause ? { cause: details.cause } : undefined);
    this.name = 'ContractSyncError';
    this.code = details.code;
    this.artifactPath = details.artifactPath;
    this.sourceLocation = details.sourceLocation;
  }
}

/**
 * Normalizes line endings to LF and ensures a single trailing newline.
 * @param {string} content
 * @returns {string}
 */
export function normalizeLineEndings(content) {
  const normalized = content.replace(/\r\n?/g, '\n').trimEnd();
  return `${normalized}\n`;
}

/**
 * Builds the deterministic generated file header with source attribution.
 * @param {string} artifactPath
 * @returns {string}
 */
export function buildGeneratedFileBanner(artifactPath) {
  return `${GENERATED_HEADER}\n// Source: ${artifactPath} (${DEFAULT_BACKEND_REPO})\n\n`;
}

/**
 * Resolves the source descriptor for a backend artifact path.
 * @param {string} artifactPath
 * @param {{ backendDir?: string; repo?: string; branch?: string }} [options]
 * @returns {{ mode: 'local' | 'remote'; artifactPath: string; location: string }}
 */
export function resolveArtifactSource(artifactPath, options = {}) {
  const normalizedArtifactPath = artifactPath
    .replace(/\\/g, '/')
    .replace(/^\/+/, '');
  const backendDir = options.backendDir?.trim();

  if (backendDir) {
    return {
      mode: 'local',
      artifactPath: normalizedArtifactPath,
      location: path.resolve(backendDir, normalizedArtifactPath),
    };
  }

  const repo = options.repo?.trim() || DEFAULT_BACKEND_REPO;
  const branch = options.branch?.trim() || DEFAULT_BACKEND_BRANCH;

  return {
    mode: 'remote',
    artifactPath: normalizedArtifactPath,
    location: `https://raw.githubusercontent.com/${repo}/${branch}/${normalizedArtifactPath}`,
  };
}

/**
 * Parses CLI arguments and environment variables for `pnpm api:sync`.
 * @param {readonly string[]} argv
 * @param {Record<string, string | undefined>} [env]
 * @returns {{ backendDir?: string; repo: string; branch: string }}
 */
export function parseSyncCliArgs(argv, env = process.env) {
  let backendDir = env.BACKEND_CHECKOUT_DIR?.trim() || undefined;
  let repo = env.BACKEND_REPO?.trim() || DEFAULT_BACKEND_REPO;
  let branch = env.BACKEND_BRANCH?.trim() || DEFAULT_BACKEND_BRANCH;

  for (let index = 0; index < argv.length; index += 1) {
    const arg = argv[index];

    if (arg === '--') {
      continue;
    }

    if (arg === '--backend-dir') {
      const next = argv[index + 1];
      if (!next || next.startsWith('--')) {
        throw new ContractSyncError(
          'Missing value for --backend-dir. Usage: pnpm api:sync -- --backend-dir <path>',
          { code: 'CLI_ARG_ERROR' },
        );
      }
      backendDir = next.trim();
      index += 1;
      continue;
    }

    if (arg.startsWith('--backend-dir=')) {
      const value = arg.slice('--backend-dir='.length).trim();
      if (!value) {
        throw new ContractSyncError(
          'Missing value for --backend-dir. Usage: pnpm api:sync -- --backend-dir <path>',
          { code: 'CLI_ARG_ERROR' },
        );
      }
      backendDir = value;
      continue;
    }

    if (arg === '--branch') {
      const next = argv[index + 1];
      if (!next || next.startsWith('--')) {
        throw new ContractSyncError(
          'Missing value for --branch. Usage: pnpm api:sync -- --branch <branch>',
          { code: 'CLI_ARG_ERROR' },
        );
      }
      branch = next.trim();
      index += 1;
      continue;
    }

    if (arg.startsWith('--branch=')) {
      const value = arg.slice('--branch='.length).trim();
      if (!value) {
        throw new ContractSyncError(
          'Missing value for --branch. Usage: pnpm api:sync -- --branch <branch>',
          { code: 'CLI_ARG_ERROR' },
        );
      }
      branch = value;
      continue;
    }

    if (arg === '--repo') {
      const next = argv[index + 1];
      if (!next || next.startsWith('--')) {
        throw new ContractSyncError(
          'Missing value for --repo. Usage: pnpm api:sync -- --repo <owner/repo>',
          { code: 'CLI_ARG_ERROR' },
        );
      }
      repo = next.trim();
      index += 1;
      continue;
    }

    if (arg.startsWith('--repo=')) {
      const value = arg.slice('--repo='.length).trim();
      if (!value) {
        throw new ContractSyncError(
          'Missing value for --repo. Usage: pnpm api:sync -- --repo <owner/repo>',
          { code: 'CLI_ARG_ERROR' },
        );
      }
      repo = value;
      continue;
    }

    throw new ContractSyncError(
      `Unknown argument "${arg}". Supported flags: --backend-dir <path>, --branch <branch>, --repo <owner/repo>`,
      { code: 'CLI_ARG_ERROR' },
    );
  }

  return {
    ...(backendDir ? { backendDir } : {}),
    repo,
    branch,
  };
}

/**
 * Fetches or reads a backend artifact, returning `{ found: false }` when missing.
 * @param {{ mode: 'local' | 'remote'; artifactPath: string; location: string }} source
 * @param {{ fetchImpl?: typeof fetch }} [options]
 * @returns {Promise<{ found: true; content: string; source: { mode: 'local' | 'remote'; artifactPath: string; location: string } } | { found: false; source: { mode: 'local' | 'remote'; artifactPath: string; location: string } }>}
 */
export async function readArtifactContent(source, options = {}) {
  if (source.mode === 'local') {
    try {
      const content = await readFile(source.location, 'utf8');
      return { found: true, content, source };
    } catch (error) {
      if (
        error &&
        typeof error === 'object' &&
        'code' in error &&
        error.code === 'ENOENT'
      ) {
        return { found: false, source };
      }

      const reason = error instanceof Error ? error.message : String(error);
      throw new ContractSyncError(
        `Failed to read backend artifact "${source.artifactPath}" at local path "${source.location}": ${reason}`,
        {
          code: 'NETWORK_ERROR',
          artifactPath: source.artifactPath,
          sourceLocation: source.location,
          cause: error,
        },
      );
    }
  }

  const fetchImpl = options.fetchImpl ?? globalThis.fetch;
  if (typeof fetchImpl !== 'function') {
    throw new ContractSyncError(
      `Cannot fetch backend artifact "${source.artifactPath}" from "${source.location}": global fetch is unavailable.`,
      {
        code: 'NETWORK_ERROR',
        artifactPath: source.artifactPath,
        sourceLocation: source.location,
      },
    );
  }

  let response;
  try {
    response = await fetchImpl(source.location);
  } catch (error) {
    const reason = error instanceof Error ? error.message : String(error);
    throw new ContractSyncError(
      `Failed to fetch backend artifact "${source.artifactPath}" from "${source.location}" (network or offline error): ${reason}. Provide a local backend checkout via --backend-dir <path> when working offline.`,
      {
        code: 'NETWORK_ERROR',
        artifactPath: source.artifactPath,
        sourceLocation: source.location,
        cause: error,
      },
    );
  }

  if (response.status === 404) {
    return { found: false, source };
  }

  if (!response.ok) {
    throw new ContractSyncError(
      `Failed to fetch backend artifact "${source.artifactPath}" from "${source.location}": HTTP ${response.status} ${response.statusText || ''}`.trim(),
      {
        code: 'NETWORK_ERROR',
        artifactPath: source.artifactPath,
        sourceLocation: source.location,
      },
    );
  }

  const content = await response.text();
  return { found: true, content, source };
}

/**
 * Parses and validates an OpenAPI 3.x JSON document string.
 * @param {string} rawText
 * @param {{ artifactPath: string; location: string }} source
 * @returns {Record<string, unknown>}
 */
export function parseAndValidateOpenApiDocument(rawText, source) {
  let parsed;
  try {
    parsed = JSON.parse(rawText);
  } catch (error) {
    const reason = error instanceof Error ? error.message : String(error);
    throw new ContractSyncError(
      `Invalid JSON in backend OpenAPI artifact "${source.artifactPath}" (${source.location}): ${reason}`,
      {
        code: 'INVALID_JSON',
        artifactPath: source.artifactPath,
        sourceLocation: source.location,
        cause: error,
      },
    );
  }

  if (
    !parsed ||
    typeof parsed !== 'object' ||
    Array.isArray(parsed) ||
    typeof parsed.openapi !== 'string' ||
    !parsed.openapi.startsWith('3.') ||
    !parsed.paths ||
    typeof parsed.paths !== 'object' ||
    Array.isArray(parsed.paths)
  ) {
    throw new ContractSyncError(
      `Backend artifact "${source.artifactPath}" (${source.location}) is not a valid OpenAPI 3.x specification (expected top-level "openapi" 3.x version string and "paths" object).`,
      {
        code: 'INVALID_OPENAPI',
        artifactPath: source.artifactPath,
        sourceLocation: source.location,
      },
    );
  }

  return parsed;
}

/**
 * Generates deterministic TypeScript source from a validated OpenAPI document.
 * @param {Record<string, unknown>} openApiDocument
 * @param {string} [artifactPath]
 * @returns {Promise<string>}
 */
export async function generateOpenApiTypes(
  openApiDocument,
  artifactPath = BACKEND_ARTIFACT_PATHS.openapi,
) {
  const ast = await openapiTS(openApiDocument);
  const body = astToString(ast);
  return normalizeLineEndings(
    `${buildGeneratedFileBanner(artifactPath)}${body}`,
  );
}

/**
 * Wraps a TypeScript contract artifact with the generated header.
 * @param {string} rawSource
 * @param {string} artifactPath
 * @returns {string}
 */
export function formatPulledTypeArtifact(rawSource, artifactPath) {
  const stripped = rawSource
    .replace(/\r\n?/g, '\n')
    .replace(
      /^\/\* eslint-disable \*\/\n\/\/ AUTO-GENERATED[^\n]*\n(?:\/\/ Source:[^\n]*\n)?\n*/,
      '',
    );
  return normalizeLineEndings(
    `${buildGeneratedFileBanner(artifactPath)}${stripped}`,
  );
}

/**
 * Synchronizes backend REST and realtime contract artifacts into the frontend repository.
 * @param {{
 *   backendDir?: string;
 *   repo?: string;
 *   branch?: string;
 *   rootDir?: string;
 *   artifactPaths?: Partial<typeof BACKEND_ARTIFACT_PATHS>;
 *   outputPaths?: Partial<typeof FRONTEND_OUTPUT_PATHS>;
 *   fetchImpl?: typeof fetch;
 *   logger?: { info?: (msg: string) => void; warn?: (msg: string) => void };
 * }} [options]
 */
export async function syncContracts(options = {}) {
  const rootDir = path.resolve(options.rootDir ?? process.cwd());
  const artifactPaths = {
    ...BACKEND_ARTIFACT_PATHS,
    ...options.artifactPaths,
  };
  const outputPaths = {
    ...FRONTEND_OUTPUT_PATHS,
    ...options.outputPaths,
  };
  const logger = options.logger ?? {};
  const warnings = [];
  const syncedFiles = [];

  const sourceOptions = {
    backendDir: options.backendDir,
    repo: options.repo,
    branch: options.branch,
  };

  // 1. Required REST OpenAPI artifact
  const openApiSource = resolveArtifactSource(
    artifactPaths.openapi,
    sourceOptions,
  );
  const openApiResult = await readArtifactContent(openApiSource, {
    fetchImpl: options.fetchImpl,
  });

  if (!openApiResult.found) {
    throw new ContractSyncError(
      `Backend OpenAPI artifact is not yet published or could not be found at "${openApiSource.artifactPath}" (${openApiSource.location}). Ensure backend issue #15 has exported openapi.json or pass --backend-dir <path>.`,
      {
        code: 'ARTIFACT_MISSING',
        artifactPath: openApiSource.artifactPath,
        sourceLocation: openApiSource.location,
      },
    );
  }

  const parsedOpenApi = parseAndValidateOpenApiDocument(
    openApiResult.content,
    openApiSource,
  );
  const generatedOpenApiTs = await generateOpenApiTypes(
    parsedOpenApi,
    openApiSource.artifactPath,
  );

  const openApiOutputPath = path.resolve(rootDir, outputPaths.openapi);
  await mkdir(path.dirname(openApiOutputPath), { recursive: true });
  await writeFile(openApiOutputPath, generatedOpenApiTs, 'utf8');
  syncedFiles.push({
    kind: 'openapi',
    source: openApiSource.location,
    outputPath: openApiOutputPath,
    relativeOutputPath: outputPaths.openapi,
  });
  logger.info?.(
    `Synced REST OpenAPI contract from ${openApiSource.location} -> ${outputPaths.openapi}`,
  );

  // 2. Shared contracts & realtime artifacts (tolerate absence until backend publishes them)
  const optionalTargets = [
    {
      kind: 'contracts',
      label: 'Shared contracts payload types',
      artifactPath: artifactPaths.contracts,
      relativeOutputPath: outputPaths.contracts,
    },
    {
      kind: 'realtimeState',
      label: 'Realtime Colyseus room-state schema types',
      artifactPath: artifactPaths.realtimeState,
      relativeOutputPath: outputPaths.realtimeState,
    },
  ];

  for (const target of optionalTargets) {
    const source = resolveArtifactSource(target.artifactPath, sourceOptions);
    const result = await readArtifactContent(source, {
      fetchImpl: options.fetchImpl,
    });

    if (!result.found) {
      const warningMessage = `${target.label} are not yet published at "${source.artifactPath}" (${source.location}); skipping ${target.relativeOutputPath}.`;
      warnings.push(warningMessage);
      logger.warn?.(warningMessage);
      continue;
    }

    const formattedContent = formatPulledTypeArtifact(
      result.content,
      source.artifactPath,
    );
    const absoluteOutputPath = path.resolve(rootDir, target.relativeOutputPath);
    await mkdir(path.dirname(absoluteOutputPath), { recursive: true });
    await writeFile(absoluteOutputPath, formattedContent, 'utf8');
    syncedFiles.push({
      kind: target.kind,
      source: source.location,
      outputPath: absoluteOutputPath,
      relativeOutputPath: target.relativeOutputPath,
    });
    logger.info?.(
      `Synced ${target.label.toLowerCase()} from ${source.location} -> ${target.relativeOutputPath}`,
    );
  }

  return {
    syncedFiles,
    warnings,
  };
}
